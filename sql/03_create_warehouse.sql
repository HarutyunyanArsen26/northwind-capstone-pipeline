-- ACA Data Analytics Capstone | 03_create_warehouse.sql
-- Target database: northwind_capstone (PostgreSQL)
-- Source: 11 supplied Northwind CSVs already ingested into stg.
-- Purpose: warehouse DDL and independent dim_date generation.
-- IMPORTANT: This file creates EMPTY business dimensions and fact_sales.
-- Data loads (MERGE/UPSERT) are intentionally separate in scripts 04 and 05.
-- Grain of fact_sales: ONE ROW PER (orderID, productID) in stg.order_details.
-- Verified on 2026-10-23: 2,155 rows and 2,155 distinct (orderID, productID) pairs.
-- All dimension join keys *_sk are surrogate, generated by PostgreSQL.
-- Calendar Date dimension covers 1990-01-01 through 9999-12-31 as ACA requests.
-- On first run the Date dimension will contain 2,925,592 dates; expect a large table.
-- Do not run in the default 'postgres' database.

BEGIN;
CREATE SCHEMA IF NOT EXISTS dw;

CREATE TABLE IF NOT EXISTS dw.dim_customer (
    customer_sk   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   TEXT NOT NULL UNIQUE,
    company_name  TEXT NOT NULL,
    contact_name  TEXT,
    city          TEXT,
    region        TEXT,
    country       TEXT,
    postal_code   TEXT
);

-- Flatten products + categories + suppliers into one Dimension.
-- Do NOT expand employee_territories in the sales join: that is many-to-many
-- and would multiply rows from fact_sales.
CREATE TABLE IF NOT EXISTS dw.dim_product (
    product_sk        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id        INTEGER NOT NULL UNIQUE,
    product_name      TEXT NOT NULL,
    category_id       INTEGER,
    category_name     TEXT,
    supplier_id       INTEGER,
    supplier_name     TEXT,
    quantity_per_unit TEXT,
    list_unit_price   NUMERIC(12, 2),
    discontinued      BOOLEAN
);

CREATE TABLE IF NOT EXISTS dw.dim_employee (
    employee_sk   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id   INTEGER NOT NULL UNIQUE,
    first_name    TEXT,
    last_name     TEXT,
    job_title     TEXT,
    hire_date     DATE,
    city          TEXT,
    country       TEXT
);

CREATE TABLE IF NOT EXISTS dw.dim_shipper (
    shipper_sk    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipper_id    INTEGER NOT NULL UNIQUE,
    company_name  TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS dw.dim_date (
    date_sk        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_date      DATE NOT NULL UNIQUE,
    calendar_year  INTEGER NOT NULL,
    quarter_number SMALLINT NOT NULL,
    month_number   SMALLINT NOT NULL,
    month_name     TEXT NOT NULL,
    year_month     TEXT NOT NULL,
    iso_week       SMALLINT NOT NULL,
    day_of_month   SMALLINT NOT NULL,
    day_of_week    SMALLINT NOT NULL,
    day_name       TEXT NOT NULL,
    is_weekend     BOOLEAN NOT NULL
);

-- Only line-level sales amounts are additive across fact rows.
-- Unit price comes from order_details.unitPrice (price actually charged),
-- NOT from products.unitPrice (catalog/list price).
-- We deliberately do NOT copy orders.freight to every line: freight belongs
-- to the whole order, so repeating it would overstate shipping totals.
-- Order ID is kept as a degenerate business identifier.
CREATE TABLE IF NOT EXISTS dw.fact_sales (
    sales_sk        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        INTEGER NOT NULL,
    customer_sk     BIGINT NOT NULL REFERENCES dw.dim_customer(customer_sk),
    product_sk      BIGINT NOT NULL REFERENCES dw.dim_product(product_sk),
    employee_sk     BIGINT REFERENCES dw.dim_employee(employee_sk),
    shipper_sk      BIGINT REFERENCES dw.dim_shipper(shipper_sk),
    order_date_sk   BIGINT NOT NULL REFERENCES dw.dim_date(date_sk),
    required_date   DATE,
    shipped_date    DATE,
    ship_city       TEXT,
    ship_country    TEXT,
    unit_price      NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
    quantity        INTEGER NOT NULL CHECK (quantity > 0),
    discount_rate   NUMERIC(5, 4) NOT NULL CHECK (discount_rate BETWEEN 0 AND 1),
    gross_sales     NUMERIC(18, 2) NOT NULL CHECK (gross_sales >= 0),
    discount_amount NUMERIC(18, 2) NOT NULL CHECK (discount_amount >= 0),
    net_sales       NUMERIC(18, 2) NOT NULL CHECK (net_sales >= 0),
    CONSTRAINT uq_fact_sales_order_product UNIQUE (order_id, product_sk)
);

-- Helpful lookup indexes for fact/dimension filters.
CREATE INDEX IF NOT EXISTS ix_fact_sales_order_date ON dw.fact_sales(order_date_sk);
CREATE INDEX IF NOT EXISTS ix_fact_sales_customer ON dw.fact_sales(customer_sk);
CREATE INDEX IF NOT EXISTS ix_fact_sales_employee ON dw.fact_sales(employee_sk);
CREATE INDEX IF NOT EXISTS ix_fact_sales_shipper ON dw.fact_sales(shipper_sk);

COMMIT;

-- Generate the required complete calendar inside DW, independently of orders.
-- Efficient for repeated runs: starts at max(full_date)+1, so a completed
-- calendar does not need to be regenerated. The UNIQUE constraint prevents duplicates.
-- On FIRST run this populates 2,925,592 dates; it may take substantial resources.
INSERT INTO dw.dim_date (
    full_date, calendar_year, quarter_number, month_number, month_name,
    year_month, iso_week, day_of_month, day_of_week, day_name, is_weekend
)
SELECT
    g.day_value::DATE AS full_date,
    EXTRACT(YEAR FROM g.day_value)::INTEGER,
    EXTRACT(QUARTER FROM g.day_value)::SMALLINT,
    EXTRACT(MONTH FROM g.day_value)::SMALLINT,
    TO_CHAR(g.day_value, 'FMMonth'),
    TO_CHAR(g.day_value, 'YYYY-MM'),
    EXTRACT(WEEK FROM g.day_value)::SMALLINT,
    EXTRACT(DAY FROM g.day_value)::SMALLINT,
    EXTRACT(ISODOW FROM g.day_value)::SMALLINT,
    TO_CHAR(g.day_value, 'FMDay'),
    (EXTRACT(ISODOW FROM g.day_value) IN (6, 7))
FROM (
    SELECT COALESCE(MAX(full_date) + 1, DATE '1990-01-01') AS next_day
    FROM dw.dim_date
) AS bounds
CROSS JOIN LATERAL generate_series(
    bounds.next_day::TIMESTAMP,
    TIMESTAMP '9999-12-31',
    INTERVAL '1 day'
) AS g(day_value)
ON CONFLICT (full_date) DO NOTHING;

-- Verification: expect 4 empty business dimensions + 1 filled dim_date + empty fact.
SELECT 'dim_customer' AS table_name, COUNT(*) AS rows_count FROM dw.dim_customer
UNION ALL SELECT 'dim_product', COUNT(*) FROM dw.dim_product
UNION ALL SELECT 'dim_employee', COUNT(*) FROM dw.dim_employee
UNION ALL SELECT 'dim_shipper', COUNT(*) FROM dw.dim_shipper
UNION ALL SELECT 'dim_date', COUNT(*) FROM dw.dim_date
UNION ALL SELECT 'fact_sales', COUNT(*) FROM dw.fact_sales
ORDER BY table_name;

-- Expected initial date bounds (on first run): 1990-01-01 to 9999-12-31
SELECT MIN(full_date) AS first_date, MAX(full_date) AS last_date,
       COUNT(*) AS calendar_days
FROM dw.dim_date;
